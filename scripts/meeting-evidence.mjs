import { deviceFlags, formatDevice } from "./meeting-system.mjs";

export function normalizeMeetingApp(value) {
  const normalized = value.toLowerCase();
  if (normalized === "zoom") return { slug: "zoom", label: "Zoom" };
  if (normalized === "meet" || normalized === "google-meet") {
    return { slug: "google-meet", label: "Google Meet" };
  }
  return { slug: "meeting", label: "Zoom / Google Meet" };
}

export function timestampForPath(date) {
  return date.toISOString().replace(/[:.]/g, "-").slice(0, 19);
}

export function smokeEvidenceFilename({ app, stamp }) {
  return `${stamp}-${app.slug}-smoke.md`;
}

export function routeSnapshotFilename({ stamp }) {
  return `${stamp}-route-snapshot.md`;
}

